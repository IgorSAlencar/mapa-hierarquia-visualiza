CREATE TABLE dbo.TB_VISITA_TRATATIVA (
    ID                           BIGINT IDENTITY(1,1) NOT NULL
        CONSTRAINT PK_TB_VISITA_TRATATIVA PRIMARY KEY,
    PARADA_ROTEIRO_ID            BIGINT NOT NULL,
    ROTEIRO_ID                   UNIQUEIDENTIFIER NOT NULL,
    VISITA_ORIGEM_ID             BIGINT NULL,
    SEQUENCIA                    SMALLINT NOT NULL
        CONSTRAINT DF_TB_VISITA_TRATATIVA_SEQUENCIA DEFAULT (1),
    EH_ATUAL                     BIT NOT NULL
        CONSTRAINT DF_TB_VISITA_TRATATIVA_EH_ATUAL DEFAULT (1),

    CHAVE_LOJA                   NVARCHAR(100) NOT NULL,
    NOME_LOJA                    NVARCHAR(250) NOT NULL,
    COD_AG                       NVARCHAR(20) NULL,
    CHAVE_SUPERVISAO             INT NOT NULL,
    ENDERECO                     NVARCHAR(500) NULL,

    COD_FUNC_RESPONSAVEL         INT NOT NULL,
    NOME_RESPONSAVEL             NVARCHAR(150) NOT NULL,
    COD_FUNC_CRIADOR             INT NOT NULL,
    NOME_CRIADOR                 NVARCHAR(150) NOT NULL,

    DATA_PLANEJADA               DATE NOT NULL,
    HORARIO_PLANEJADO            TIME(0) NULL,
    FUSO_HORARIO                 VARCHAR(64) NOT NULL
        CONSTRAINT DF_TB_VISITA_TRATATIVA_FUSO DEFAULT ('America/Sao_Paulo'),
    PRIORIDADE                   VARCHAR(10) NOT NULL
        CONSTRAINT DF_TB_VISITA_TRATATIVA_PRIORIDADE DEFAULT ('NORMAL'),
    ORIENTACAO                   NVARCHAR(1000) NULL,

    STATUS                       VARCHAR(20) NOT NULL
        CONSTRAINT DF_TB_VISITA_TRATATIVA_STATUS DEFAULT ('PENDENTE'),
    RESPOSTA_REALIZACAO          VARCHAR(20) NULL,
    RESULTADO_COMERCIAL          VARCHAR(30) NOT NULL
        CONSTRAINT DF_TB_VISITA_TRATATIVA_RESULTADO DEFAULT ('SEM_RESULTADO'),
    DATA_VISITA                  DATE NULL,
    INICIO_EM_UTC                DATETIME2(3) NULL,
    TERMINO_EM_UTC               DATETIME2(3) NULL,
    MOTIVO_NAO_REALIZACAO        VARCHAR(40) NULL,
    JUSTIFICATIVA_NAO_REALIZACAO NVARCHAR(1000) NULL,
    OBSERVACAO_GERAL             NVARCHAR(2000) NULL,
    NECESSITA_RETORNO            BIT NOT NULL
        CONSTRAINT DF_TB_VISITA_TRATATIVA_NECESSITA_RETORNO DEFAULT (0),
    DATA_PREVISTA_RETORNO        DATE NULL,

    SALVO_PARCIAL_EM_UTC         DATETIME2(3) NULL,
    FINALIZADA_EM_UTC            DATETIME2(3) NULL,
    FINALIZADA_POR               INT NULL,
    CRIADO_EM_UTC                DATETIME2(3) NOT NULL
        CONSTRAINT DF_TB_VISITA_TRATATIVA_CRIADO_EM_UTC DEFAULT (SYSUTCDATETIME()),
    CRIADO_POR                   INT NOT NULL,
    ATUALIZADO_EM_UTC            DATETIME2(3) NOT NULL
        CONSTRAINT DF_TB_VISITA_TRATATIVA_ATUALIZADO_EM_UTC DEFAULT (SYSUTCDATETIME()),
    ATUALIZADO_POR               INT NOT NULL,
    VERSAO_LINHA                 ROWVERSION,

    CONSTRAINT FK_TB_VISITA_TRATATIVA_PARADA_ROTEIRO
        FOREIGN KEY (PARADA_ROTEIRO_ID, ROTEIRO_ID)
        REFERENCES dbo.ROTEIRO_PARADAS_MAPA(ID, ROTEIRO_ID),
    CONSTRAINT FK_TB_VISITA_TRATATIVA_ROTEIRO
        FOREIGN KEY (ROTEIRO_ID) REFERENCES dbo.ROTEIROS_MAPA(ID),
    CONSTRAINT FK_TB_VISITA_TRATATIVA_ORIGEM
        FOREIGN KEY (VISITA_ORIGEM_ID) REFERENCES dbo.TB_VISITA_TRATATIVA(ID),

    CONSTRAINT CK_TB_VISITA_TRATATIVA_SEQUENCIA
        CHECK (SEQUENCIA > 0),
    CONSTRAINT CK_TB_VISITA_TRATATIVA_STATUS
        CHECK (STATUS IN (
            'PENDENTE', 'EM_ANDAMENTO', 'REALIZADA',
            'NAO_REALIZADA', 'REAGENDADA', 'CANCELADA'
        )),
    CONSTRAINT CK_TB_VISITA_TRATATIVA_RESPOSTA
        CHECK (
            RESPOSTA_REALIZACAO IS NULL OR
            RESPOSTA_REALIZACAO IN ('SIM', 'NAO', 'REAGENDADA')
        ),
    CONSTRAINT CK_TB_VISITA_TRATATIVA_PRIORIDADE
        CHECK (PRIORIDADE IN ('BAIXA', 'NORMAL', 'ALTA', 'CRITICA')),
    CONSTRAINT CK_TB_VISITA_TRATATIVA_RESULTADO
        CHECK (RESULTADO_COMERCIAL IN (
            'SEM_RESULTADO', 'APRESENTADO', 'INTERESSE', 'PROPOSTA',
            'CONTRATADO', 'TRANSACIONOU', 'SEM_INTERESSE',
            'SEM_OPORTUNIDADE', 'OUTRO'
        )),
    CONSTRAINT CK_TB_VISITA_TRATATIVA_PERIODO
        CHECK (
            INICIO_EM_UTC IS NULL OR TERMINO_EM_UTC IS NULL OR
            TERMINO_EM_UTC >= INICIO_EM_UTC
        ),
    CONSTRAINT CK_TB_VISITA_TRATATIVA_OUTRO
        CHECK (
            MOTIVO_NAO_REALIZACAO <> 'OUTRO' OR
            NULLIF(LTRIM(RTRIM(JUSTIFICATIVA_NAO_REALIZACAO)), N'') IS NOT NULL
        ),
    CONSTRAINT CK_TB_VISITA_TRATATIVA_REALIZADA
        CHECK (
            STATUS <> 'REALIZADA' OR
            (
                RESPOSTA_REALIZACAO = 'SIM' AND
                DATA_VISITA IS NOT NULL AND
                INICIO_EM_UTC IS NOT NULL AND
                FINALIZADA_EM_UTC IS NOT NULL AND
                FINALIZADA_POR IS NOT NULL
            )
        ),
    CONSTRAINT CK_TB_VISITA_TRATATIVA_NAO_REALIZADA
        CHECK (
            STATUS <> 'NAO_REALIZADA' OR
            (
                RESPOSTA_REALIZACAO = 'NAO' AND
                MOTIVO_NAO_REALIZACAO IS NOT NULL AND
                FINALIZADA_EM_UTC IS NOT NULL AND
                FINALIZADA_POR IS NOT NULL
            )
        ),
    CONSTRAINT CK_TB_VISITA_TRATATIVA_REAGENDADA
        CHECK (
            STATUS <> 'REAGENDADA' OR
            (
                RESPOSTA_REALIZACAO = 'REAGENDADA' AND
                FINALIZADA_EM_UTC IS NOT NULL AND
                FINALIZADA_POR IS NOT NULL AND
                EH_ATUAL = 0
            )
        ),
    CONSTRAINT CK_TB_VISITA_TRATATIVA_CANCELADA
        CHECK (
            STATUS <> 'CANCELADA' OR
            (
                FINALIZADA_EM_UTC IS NOT NULL AND
                FINALIZADA_POR IS NOT NULL
            )
        )
);

