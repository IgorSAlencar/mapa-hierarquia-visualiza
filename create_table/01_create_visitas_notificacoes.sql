    CONSTRAINT FK_TB_VISITA_CHECKIN_VISITA
        FOREIGN KEY (VISITA_ID) REFERENCES dbo.TB_VISITA_TRATATIVA(ID),
    CONSTRAINT UQ_TB_VISITA_CHECKIN_DISPOSITIVO_EVENTO
        UNIQUE (DISPOSITIVO_EVENTO_ID),
    CONSTRAINT CK_TB_VISITA_CHECKIN_TIPO
        CHECK (TIPO IN ('CHECKIN', 'CHECKOUT')),
    CONSTRAINT CK_TB_VISITA_CHECKIN_OFFSET
        CHECK (FUSO_OFFSET_MINUTOS BETWEEN -840 AND 840),
    CONSTRAINT CK_TB_VISITA_CHECKIN_COORDENADAS
        CHECK (
            (LATITUDE IS NULL AND LONGITUDE IS NULL) OR
            (
                LATITUDE IS NOT NULL AND
                LONGITUDE IS NOT NULL AND
                LATITUDE BETWEEN -90 AND 90 AND
                LONGITUDE BETWEEN -180 AND 180
            )
        ),
    CONSTRAINT CK_TB_VISITA_CHECKIN_COORDENADAS_LOJA
        CHECK (
            (LATITUDE_LOJA IS NULL AND LONGITUDE_LOJA IS NULL) OR
            (
                LATITUDE_LOJA IS NOT NULL AND
                LONGITUDE_LOJA IS NOT NULL AND
                LATITUDE_LOJA BETWEEN -90 AND 90 AND
                LONGITUDE_LOJA BETWEEN -180 AND 180
            )
        ),
    CONSTRAINT CK_TB_VISITA_CHECKIN_METRICAS
        CHECK (
            (PRECISAO_METROS IS NULL OR PRECISAO_METROS >= 0) AND
            (DISTANCIA_METROS IS NULL OR DISTANCIA_METROS >= 0) AND
            (RAIO_PERMITIDO_METROS IS NULL OR RAIO_PERMITIDO_METROS >= 0)
        ),
    CONSTRAINT CK_TB_VISITA_CHECKIN_STATUS
        CHECK (STATUS_VALIDACAO IN (
            'VALIDADO', 'FORA_DO_RAIO', 'SEM_GEOLOCALIZACAO',
            'PENDENTE_VALIDACAO', 'REJEITADO', 'NAO_APLICAVEL'
        )),
    CONSTRAINT CK_TB_VISITA_CHECKIN_ORIGEM
        CHECK (ORIGEM IN ('GPS', 'REDE', 'MANUAL', 'OFFLINE', 'SISTEMA')),
    CONSTRAINT CK_TB_VISITA_CHECKIN_EXCECAO
        CHECK (
            STATUS_VALIDACAO NOT IN ('FORA_DO_RAIO', 'SEM_GEOLOCALIZACAO') OR
            NULLIF(LTRIM(RTRIM(JUSTIFICATIVA_EXCECAO)), N'') IS NOT NULL
        )
